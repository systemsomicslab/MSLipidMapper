testServer(function(input, output, session) {
  settings <- reactiveVal(list(plot_type = "dot", hm_topN = 10L, hm_row_z = TRUE, order_by = "none"))
  adv_reactive <- reactive(settings())
  se_work <- reactiveVal(list(version = 1L))
  selected_class <- reactiveVal("PC")
  eval(lower)
  eval(heatmap)
  runs <- reactiveVal(0L)
  observe({ heatmap_components(); runs(isolate(runs()) + 1L) })
}, {
  session$flushReact()
  before <- runs()
  settings(modifyList(settings(), list(plot_type = "violin")))
  session$flushReact()
  stopifnot(runs() == before)
  settings(modifyList(settings(), list(hm_topN = 20L)))
  session$flushReact()
  stopifnot(runs() == before + 1L, heatmap_components()$ht$topN == 20L)
  selected_class("PE")
  session$flushReact()
  stopifnot(runs() == before + 2L, heatmap_components()$ht$class_name == "PE")
  settings(modifyList(settings(), list(palette_map = c(A = "green"))))
  session$flushReact()
  stopifnot(runs() == before + 3L)
})
