testthat::test_that("browser separates drafts and releases and loads provenance", {
  catalog <- .pathway_browser_catalog()
  testthat::expect_true(all(c("release", "draft") %in% catalog$kind))
  draft <- .pathway_browser_read(catalog[catalog$key == "draft:mouse-lipid-2026-10-15", , drop = FALSE])
  testthat::expect_equal(nrow(draft$reactions), 41)
  testthat::expect_true(file.exists(draft$rdf))
  testthat::expect_true(length(draft$details[[1]]$protein_evidence) > 0)
  testthat::expect_equal(nrow(.pathway_browser_filter(draft$classes, "GP0101")), 1)
  testthat::expect_equal(nrow(.pathway_browser_filter(draft$reactions, "[.*")), 0)
  testthat::expect_equal(nrow(.pathway_browser_filter(draft$reactions, "RHEA:11164")), 1)
  released <- .pathway_browser_read(catalog[which(catalog$kind == "release" & catalog$release == "0.4.0" & catalog$taxon == "10090")[1], , drop = FALSE])
  testthat::expect_true(nrow(released$reactions) > 0)
  testthat::expect_true("sources_json" %in% names(released$details[[1]]$reaction))
})

testthat::test_that("comprehensive collection searches canonical classes and retains source detail", {
  catalog <- .pathway_browser_catalog()
  entry <- catalog[grepl("mouse-lipid-census-", catalog$key), , drop = FALSE]
  testthat::expect_equal(nrow(entry), 1)
  x <- .pathway_browser_read(entry)
  testthat::expect_equal(nrow(x$reactions), as.integer(x$metadata$candidate_count))
  testthat::expect_true(all(grepl("/MSLMC", x$classes$uri)))
  testthat::expect_gt(nrow(.pathway_browser_filter(x$classes, "GP1001")), 0)
  testthat::expect_true(any(x$reactions$status == "partial-or-unmapped"))
  testthat::expect_equal(basename(x$rdf), "class-pathways.ttl")
  testthat::expect_equal(basename(x$source_rdf), "candidates.ttl")
})

testthat::test_that("standalone server searches related reactions and handles selection", {
  app <- pathway_database_app()
  testthat::expect_s3_class(app, "shiny.appobj")
  catalog <- .pathway_browser_catalog()
  draft_key <- "draft:mouse-lipid-2026-10-15"
  shiny::testServer(app$serverFuncSource(), {
    session$setInputs(dataset = draft_key, query = "GP0101")
    testthat::expect_equal(nrow(classes()), 1)
    testthat::expect_gt(nrow(reactions()), 0)
    session$setInputs(reactions_rows_selected = 1L)
    testthat::expect_match(output$detail, "protein_evidence")
    session$setInputs(query = "no-such-reaction-123")
    testthat::expect_equal(nrow(reactions()), 0)
    testthat::expect_match(output$detail, "Select a reaction")
    release_key <- catalog$key[which(catalog$kind == "release" & catalog$release == "0.4.0" & catalog$taxon == "10090")[1]]
    session$setInputs(dataset = release_key, query = "GP0101", reactions_rows_selected = integer())
    testthat::expect_gt(nrow(reactions()), 0)
    testthat::expect_match(output$metadata, "10090")
  })
})

testthat::test_that("integrated mouse catalog searches sources and matching records independently", {
  catalog <- .pathway_browser_catalog()
  entry <- catalog[catalog$key == "draft:mouse-integrated-2026-10-15", , drop = FALSE]
  testthat::expect_equal(nrow(entry), 1)
  x <- .pathway_browser_read(entry)
  testthat::expect_equal(nrow(x$reactions), 3661)
  testthat::expect_equal(sum(x$reactions$source_database == "Rhea"), 2950)
  testthat::expect_equal(sum(x$reactions$source_database == "Reactome"), 711)
  testthat::expect_equal(nrow(x$matches), 1049)
  testthat::expect_true(all(c("class-signature", "exact-chemical-equation") %in% x$matches$kind))
  shiny::testServer(pathway_database_app()$serverFuncSource(), {
    session$setInputs(dataset = entry$key, source = "All", query = "GP0101")
    testthat::expect_equal(sort(unique(reactions()$source_database)), c("Reactome", "Rhea"))
    session$setInputs(source = "Rhea")
    testthat::expect_true(all(reactions()$source_database == "Rhea"))
    session$setInputs(source = "Reactome", reactions_rows_selected = 1L)
    testthat::expect_true(all(reactions()$source_database == "Reactome"))
    testthat::expect_match(output$detail, "is_inferred")
    session$setInputs(source = "All", query = "no-such-reaction-123")
    testthat::expect_equal(nrow(reactions()), 0)
  })
})

