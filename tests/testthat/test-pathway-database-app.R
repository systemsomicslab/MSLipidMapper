testthat::test_that("mapping view uses pathway evidence and measured classes", {
  catalog <- .pathway_browser_catalog()
  entry <- catalog[catalog$key == "draft:mouse-integrated-2026-10-15", , drop = FALSE]
  x <- .pathway_browser_read(entry)
  ids <- x$reactions$uri
  testthat::expect_length(.pathway_mapping_filter(x, ids, pathways = "R-MMU-428157", profile = "mapping"), 21L)
  testthat::expect_length(.pathway_mapping_filter(x, ids, pathways = "R-MMU-428157", profile = "mapping", candidates = "equation"), 27L)
  testthat::expect_length(.pathway_mapping_filter(x, ids, pathways = "R-MMU-428157", profile = "mapping", candidates = "all"), 38L)
  testthat::expect_length(.pathway_mapping_filter(x, ids, pathways = "R-MMU-428157", profile = "mapping", include_inferred = FALSE), 0L)
  shiny::testServer(pathway_database_app()$serverFuncSource(), {
    session$setInputs(dataset = entry$key, profile = "mapping", pathway = "R-MMU-1483206", membership = "none", query = "", source = "All")
    testthat::expect_equal(nrow(reactions()), 25L)
    testthat::expect_true(all(reactions()$source_database == "Reactome"))
    session$setInputs(membership = "all")
    testthat::expect_equal(nrow(reactions()), 106L)
    testthat::expect_true(any(grepl("candidate", reactions()$pathway_membership_evidence)))
  })
  make_row <- function(id, a, b) list(reaction = id, classes = list(
    list(canonical_class = a, side_code = "L"), list(canonical_class = b, side_code = "R")))
  fixture <- list(details = list(make_row("AX", "A", "X"), make_row("XB", "X", "B"), make_row("XC", "X", "C")))
  testthat::expect_setequal(.pathway_mapping_filter(fixture, c("AX", "XB", "XC"), measured = c("A", "B"), measured_mode = "bridge", bridge_depth = 4L), c("AX", "XB"))
  testthat::expect_length(.pathway_mapping_filter(fixture, c("AX", "XB", "XC"), measured = c("A", "B"), measured_mode = "both"), 0L)
  lines <- .pathway_mapping_turtle(x, .pathway_mapping_filter(x, ids, pathways = "R-MMU-1483206", profile = "mapping"))
  testthat::expect_equal(sum(grepl("a mslm:ReactionTraversalProjection", lines, fixed = TRUE)), 25L)
  testthat::expect_true(any(grepl("mslm:sourceDatabase", lines, fixed = TRUE)))
})
